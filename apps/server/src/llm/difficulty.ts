export const MIN_DIFFICULTY = 1;
export const MAX_DIFFICULTY = 5;

export function getDifficulty(level: number): DifficultyLevel {
  const clamped = Math.min(Math.max(Math.round(level), MIN_DIFFICULTY), MAX_DIFFICULTY);
  // 上面的 clamp 保证了索引一定落在范围内
  return DIFFICULTY_LEVELS[clamped - 1]!;
}
